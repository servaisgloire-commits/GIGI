-- DSI-001 FAST: staged pre-tests with CI-backed evidence.
-- Proposal only: no production DB changes until separate release approval.
CREATE TABLE IF NOT EXISTS dsi_ops.pretest_results (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 incident_id bigint NOT NULL REFERENCES dsi_ops.incidents(id),
 run_number integer NOT NULL CHECK (run_number >= 0),
 stage text NOT NULL CHECK (stage IN ('pretest_functional','pretest_security')),
 tester text NOT NULL,
 revision_sha text NOT NULL CHECK (revision_sha ~ '^[0-9a-fA-F]{40}$'),
 ci_run_url text NOT NULL CHECK (ci_run_url LIKE 'https://github.com/%/actions/runs/%'),
 source text NOT NULL DEFAULT 'github_actions' CHECK (source = 'github_actions'),
 passed boolean NOT NULL,
 evidence jsonb NOT NULL DEFAULT '{}'::jsonb,
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE (incident_id,run_number,stage,revision_sha)
);
ALTER TABLE dsi_ops.pretest_results ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON dsi_ops.pretest_results FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON dsi_ops.pretest_results TO service_role;
GRANT USAGE, SELECT ON SEQUENCE dsi_ops.pretest_results_id_seq TO service_role;

-- Expand stage constraint without discarding any incident, task or message.
ALTER TABLE dsi_ops.agent_tasks DROP CONSTRAINT IF EXISTS agent_tasks_stage_check;
ALTER TABLE dsi_ops.agent_tasks ADD CONSTRAINT agent_tasks_stage_check
 CHECK (stage IN ('diagnosis','pretest_functional','pretest_security','security_review','functional_test_plan'));

-- An LLM-generated pre-test plan never counts as execution.
-- Security review is blocked until TWO independent CI proofs are PASSED on the SAME SHA.
CREATE OR REPLACE FUNCTION public.dsi_agent_claim(p_token text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'pg_catalog', 'dsi_ops', 'public', 'vault'
AS $function$
DECLARE authentic boolean; item record; previous_analysis text; previous_security text; previous_pretest_functional text; previous_pretest_security text;
BEGIN
 authentic := (p_token IS NOT NULL AND length(p_token)=64
  AND p_token=(SELECT decrypted_secret FROM vault.decrypted_secrets WHERE name='dsi_dispatch_token_v1' LIMIT 1));
 IF NOT authentic THEN RETURN jsonb_build_object('ok',false,'error','UNAUTHORIZED'); END IF;
 INSERT INTO dsi_ops.agent_tasks(incident_id,organization,stage,assigned_agent,run_number)
 SELECT i.id,i.organization,st.stage,st.who,i.reopens
 FROM dsi_ops.incidents i CROSS JOIN LATERAL (
  VALUES ('diagnosis',i.owner_agent),('pretest_functional','Émile'),('pretest_security','Camille'),('security_review',i.security_tester),('functional_test_plan',i.functional_tester)
 ) AS st(stage,who)
 WHERE i.state='open' AND EXISTS(SELECT 1 FROM dsi_ops.settings s WHERE s.organization=i.organization AND s.monitor_enabled)
 ON CONFLICT(incident_id,stage,run_number) DO NOTHING;
 SELECT t.id,t.incident_id,t.organization,t.stage,t.assigned_agent,t.run_number,
        i.category,i.title,i.description,i.severity INTO item
 FROM dsi_ops.agent_tasks t JOIN dsi_ops.incidents i ON i.id=t.incident_id
 WHERE t.status='queued' AND i.state='open' AND t.run_number=i.reopens
 AND (
  t.stage='diagnosis'
  OR (t.stage='pretest_functional' AND EXISTS (
   SELECT 1 FROM dsi_ops.agent_tasks prev
   WHERE prev.incident_id=t.incident_id AND prev.run_number=t.run_number
     AND prev.stage='diagnosis' AND prev.status='completed'))
  OR (t.stage='pretest_security' AND EXISTS (
   SELECT 1 FROM dsi_ops.agent_tasks prev
   WHERE prev.incident_id=t.incident_id AND prev.run_number=t.run_number
     AND prev.stage='pretest_functional' AND prev.status='completed'))
  OR (t.stage='security_review' AND EXISTS (
   SELECT 1 FROM dsi_ops.agent_tasks prev
   WHERE prev.incident_id=t.incident_id AND prev.run_number=t.run_number
     AND prev.stage='pretest_security' AND prev.status='completed')
   AND EXISTS (
    SELECT 1 FROM dsi_ops.pretest_results pf
    JOIN dsi_ops.pretest_results ps
      ON ps.incident_id=pf.incident_id AND ps.run_number=pf.run_number
     AND ps.revision_sha=pf.revision_sha
    WHERE pf.incident_id=t.incident_id AND pf.run_number=t.run_number
      AND pf.stage='pretest_functional' AND ps.stage='pretest_security'
      AND pf.tester='Émile' AND ps.tester='Camille'
      AND pf.passed=true AND ps.passed=true
      AND pf.source='github_actions' AND ps.source='github_actions'
   ))
  OR (t.stage='functional_test_plan' AND EXISTS (
   SELECT 1 FROM dsi_ops.agent_tasks prev
   WHERE prev.incident_id=t.incident_id AND prev.run_number=t.run_number
     AND prev.stage='security_review' AND prev.status='completed'))
 )
 ORDER BY t.created_at,t.id LIMIT 1 FOR UPDATE OF t SKIP LOCKED;
 IF NOT FOUND THEN RETURN jsonb_build_object('ok',true,'task',null); END IF;
 UPDATE dsi_ops.agent_tasks SET status='working',started_at=now(),attempts=attempts+1 WHERE id=item.id;
 SELECT left(output,1800) INTO previous_analysis FROM dsi_ops.agent_tasks
 WHERE incident_id=item.incident_id AND run_number=item.run_number AND stage='diagnosis' AND status='completed' LIMIT 1;
 SELECT left(output,1800) INTO previous_security FROM dsi_ops.agent_tasks
 WHERE incident_id=item.incident_id AND run_number=item.run_number AND stage='security_review' AND status='completed' LIMIT 1;
 SELECT left(output,1800) INTO previous_pretest_functional FROM dsi_ops.agent_tasks
 WHERE incident_id=item.incident_id AND run_number=item.run_number AND stage='pretest_functional' AND status='completed' LIMIT 1;
 SELECT left(output,1800) INTO previous_pretest_security FROM dsi_ops.agent_tasks
 WHERE incident_id=item.incident_id AND run_number=item.run_number AND stage='pretest_security' AND status='completed' LIMIT 1;
 RETURN jsonb_build_object('ok',true,'task',jsonb_build_object(
   'id',item.id,'incident_id',item.incident_id,'organization',item.organization,
   'run_number',item.run_number,'stage',item.stage,'agent',item.assigned_agent,
   'category',item.category,'title',left(item.title,200),
   'description',left(coalesce(item.description,''),1500),'severity',item.severity,
   'previous_diagnosis',coalesce(previous_analysis,''),'previous_security_review',coalesce(previous_security,''),
   'previous_pretest_functional',coalesce(previous_pretest_functional,''),
   'previous_pretest_security',coalesce(previous_pretest_security,'')));
END $function$


REVOKE ALL ON FUNCTION public.dsi_agent_claim(text) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.dsi_agent_claim(text) TO service_role;
